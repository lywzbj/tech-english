package com.techenglish.vocabulary;

import jakarta.validation.Valid;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

import java.util.List;

public final class VocabularyDtos {

    private VocabularyDtos() {
    }

    public record VocabCard(
            Long userVocabId,
            Long vocabId,
            String lemma,
            String pos,
            String phonetic,
            String definitionEn,
            String definitionZh,
            String exampleEn,
            String exampleZh,
            String contextSentence,
            String status,
            int intervalDays,
            String nextReviewAt
    ) {
    }

    public record DueResponse(long dueCount, List<VocabCard> cards) {
    }

    public record ReviewRequest(@Min(0) @Max(3) int rating) {
    }

    public record ReviewResponse(
            Long userVocabId,
            String nextReviewAt,
            int intervalDays,
            String status,
            long remainingDue
    ) {
    }

    /**
     * Dictionary words keep their curated definitions. For a word outside the seed
     * dictionary the caller may supply a definition (typically generated by AI), and
     * a reading-sourced vocab entry is created on demand.
     */
    public record AddVocabRequest(
            @NotBlank @Size(max = 120) String lemma,
            @Size(max = 1000) String contextSentence,
            @Size(max = 500) String definitionZh,
            @Size(max = 500) String definitionEn,
            @Size(max = 20) String pos,
            /** How the word reached the deck (e.g. "manual", "post-review"); recorded on the learning event. */
            @Size(max = 40) String origin,
            /** Source document label, e.g. the article title for a reading-sourced word. */
            @Size(max = 120) String sourceDoc
    ) {
    }

    /**
     * Post-reading settlement batch import. Items already in the learner's deck are
     * merged silently and flagged in the result, so the sheet can submit everything
     * without a 409 dance on the client.
     */
    public record BatchAddRequest(@Valid @Size(max = 50) List<AddVocabRequest> items) {
    }

    public record BatchItemResult(
            String lemma,
            Long userVocabId,
            Long vocabId,
            boolean alreadyInDeck,
            String status,
            int intervalDays
    ) {
    }

    public record BatchAddResponse(int total, int added, int alreadyInDeck, List<BatchItemResult> results) {
    }

    public record LookupResponse(
            Long vocabId,
            String lemma,
            String pos,
            String phonetic,
            String definitionEn,
            String definitionZh,
            String exampleEn,
            String exampleZh,
            String category,
            String domain,
            boolean inDeck
    ) {
    }

    public record VocabularyListResponse(long total, long dueCount, List<VocabCard> words) {
    }
}
